#: Groups as plain JSON-friendly data (the API hands this to the phone).
def emoji_payload() -> list[dict[str, object]]:
    """``[{"title": ..., "emoji": [...]}, ...]`` for ``/api/emoji``."""
    return [{"title": title, "emoji": list(group)} for title, group in EMOJI_GROUPS]


