"""The emoji palette, in one place.

Three clients send emoji (the desktop window, the phone page and the Android
app) and they must offer the same set -- a face you can send from the phone but
not from the desktop is a bug report waiting to happen.  The list therefore
lives here, the desktop imports it, the web page and the app fetch it over
``/api/emoji``, and a self-test check fails if those three ever disagree.

Only real Unicode emoji belong here: they render with the platform's own font,
so what the sender sees is what the receiver sees, on every device, with no
image files to ship.
"""

